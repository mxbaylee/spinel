import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync, existsSync, createReadStream, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const root='/tmp/spn143-hosted', prefix='docs/review-assets/spn-143-acceptance-96b11bf0';
const identity=JSON.parse(readFileSync(root+'/identities.json','utf8'));
const run=JSON.parse(readFileSync(root+'/ci-run.json','utf8'));
assert.equal(run.status,'completed'); assert.equal(run.conclusion,'success');
assert.equal(run.head_sha,identity.source); assert.equal(run.run_attempt,1);
const jobs=JSON.parse(readFileSync(root+'/ci-jobs.json','utf8')).flatMap((p:any)=>p.jobs);
assert.equal(jobs.length,33); assert.ok(jobs.every((j:any)=>j.conclusion==='success' && j.head_sha===identity.source));
const story=JSON.parse(readFileSync(root+'/storybook-run.json','utf8'));
assert.equal(story.conclusion,'success'); assert.equal(story.head_sha,identity.source); assert.equal(story.run_attempt,1);
for(const n of ['desktop-acceptance-a.md','mobile-acceptance-b.md','callback-desktop-acceptance-a.md','callback-mobile-acceptance-b.md','final-readiness-a.md','final-readiness-b.md','README.md','mobile.zip','callback-mobile-package.json']) assert.ok(existsSync(root+'/'+n),n);
const required=['Pull request','Backlog','Lint','Typecheck','Unit tests','Lib tests','Playwright smoke'];
const gates=jobs.filter((j:any)=>required.includes(j.name)); assert.equal(gates.length,7);
writeFileSync(root+'/required-gates.json',JSON.stringify(gates.map((j:any)=>({id:j.id,name:j.name,conclusion:j.conclusion,html_url:j.html_url})),null,2)+'\n');
const omitted=new Set(['callback-desktop.zip','callback-mobile.zip','archive-commit.txt','SHA256SUMS','final-body.md']);
const files=readdirSync(root,{recursive:true,withFileTypes:true}).filter(e=>e.isFile()).map(e=>`${e.parentPath}/${e.name}`.slice(root.length+1)).filter(n=>!omitted.has(n)&&!n.startsWith('callback-desktop/')&&!n.startsWith('callback-mobile/')).sort();
assert.ok(!files.some(n=>n.includes('.sqlite')));
const lines:string[]=[];
for(const n of files){ assert.ok(statSync(root+'/'+n).size<100*1024*1024,n); const hash=createHash('sha256'); for await(const chunk of createReadStream(root+'/'+n,{highWaterMark:65536}))hash.update(chunk); lines.push(`${hash.digest('hex')}  ${n}`); }
writeFileSync(root+'/SHA256SUMS',lines.join('\n')+'\n');
const env={...process.env,GIT_INDEX_FILE:'/tmp/spn143-final.index'};
const git=(...a:string[])=>execFileSync('git',a,{env,encoding:'utf8'}).trim();
git('read-tree','--empty');
for(const n of [...files,'SHA256SUMS'])git('update-index','--add','--cacheinfo','100644',git('hash-object','-w',root+'/'+n),prefix+'/'+n);
const commit=git('commit-tree',git('write-tree'),'-m','Preserve first-attempt SPN-143 acceptance for 96b11bf0');
writeFileSync(root+'/archive-commit.txt',commit+'\n'); console.log(commit);
