import { readFileSync, writeFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
const file = '/tmp/spn090-publication-724b5777/collect-hosted.ts';
const source = readFileSync(file, 'utf8');
const idLine = source.split('\n').find((line) => line.includes('.every((v) =>'))!;
const expression = idLine.match(/=> (.+)\.test\(v/)![1];
const matcher = runInNewContext(expression) as RegExp;
assert(matcher.test('43512345678'));
assert(!matcher.test('abc'));
assert(!matcher.test('\\ddd'));
const splitLine = source.split('\n').find((line) => line.includes("execFileSync('unzip', ['-Z1'"))!;
const splitExpression = splitLine.match(/\.split\((.+?)\)\.filter/)![1];
const delimiter = runInNewContext(splitExpression) as string;
assert.equal(delimiter, '\n');
assert.deepEqual('manifest.json\nreadme.txt\nreport.json\n'.split(delimiter).filter((name) => name.endsWith('.json')), ['manifest.json', 'report.json']);
const report = { at: new Date().toISOString(), sourceSha256: createHash('sha256').update(source).digest('hex'), numericExpression: expression, numericExpressionBackslashCount: expression.split('\\').length - 1, acceptsDecimalRunIds: true, rejectsLettersAndLiteralBackslashD: true, delimiterCodepoints: [...delimiter].map((c) => c.codePointAt(0)), multiLineJsonSelection: true, networkCalls: 0, note: 'The expanded current collector already contains single source escapes. This probe evaluates only its extracted parser expressions; it does not import/execute the collector or claim full collection validation.' };
writeFileSync('/tmp/spn090-publication-724b5777/collector-parser-probe.json', JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report));
